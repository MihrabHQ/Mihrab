#!/usr/bin/env node
/**
 * One widget contract, three languages.
 *
 * Reads scripts/contract/widget-contract.js and writes:
 *
 *   src/widget/contract.generated.ts                       the app's types
 *   ios/Contract/WidgetContract.generated.swift            Codable structs
 *   android/app/src/main/java/com/prayer_times/contract/WidgetContract.kt
 *                                                          data classes
 *
 * The readers it writes are lenient by construction — see the rules at the
 * top of the contract file. That is the point of generating them rather
 * than writing them: the Live Activity's hand-written decoder was strict
 * about one field the app sometimes left out, and on a 24-hour clock no
 * Live Activity ever appeared. A generated reader cannot forget the rule.
 *
 * Run `npm run gen-widget-contract`. `--check` compares instead of writing,
 * which is what the jest test runs, so a contract edited without
 * regenerating fails the suite.
 *
 * Why not quicktype (tried on the real payload, 2026-09-28): its Swift is
 * synthesized `Codable`, where one mistyped optional fails the whole
 * payload — the exact bug this replaces — and its Kotlin needs Jackson,
 * Klaxon or kotlinx.serialization, where the app reads JSON with the
 * platform's own org.json and nothing else.
 */

