// ---------------------------------------------------------------- model

/** Normalise the contract and refuse anything the generators cannot mean. */
function load(contract) {
  const types = contract.types.map(tp => ({
    name: tp.name,
    doc: tp.doc || '',
    fields: tp.fields.map(([name, spec, doc]) => ({
      name,
      spec,
      doc: doc || '',
      mode: spec.required
        ? 'required'
        : 'default' in spec
        ? 'default'
        : 'nullable',
    })),
  }));
  const byName = new Map(types.map(tp => [tp.name, tp]));
  const enums = new Map();

  const check = (cond, msg) => {
    if (!cond) throw new Error(`widget contract: ${msg}`);
  };

  const walk = (owner, field, spec) => {
    if (spec.kind === 'ref') {
      check(
        byName.has(spec.name),
        `${owner}.${field}: unknown type ${spec.name}`,
      );
    }
    if (spec.kind === 'list') {
      check(
        spec.of.kind !== 'list',
        `${owner}.${field}: lists of lists are not supported`,
      );
      walk(owner, field, spec.of);
    }
    if (spec.kind === 'enum') {
      const name = spec.name || `${owner}${cap(field)}`;
      spec.enumName = name;
      const prior = enums.get(name);
      check(
        !prior || prior.join('|') === spec.values.join('|'),
        `enum ${name} declared twice with different values`,
      );
      enums.set(name, spec.values);
    }
  };

  for (const tp of types) {
    const seen = new Set();
    for (const f of tp.fields) {
      check(!seen.has(f.name), `${tp.name}.${f.name} declared twice`);
      seen.add(f.name);
      walk(tp.name, f.name, f.spec);
      if (f.mode === 'default') {
        const d = f.spec.default;
        if (f.spec.kind === 'ref') {
          check(
            d === 'fallback',
            `${tp.name}.${f.name}: a type's only default is 'fallback'`,
          );
        } else if (f.spec.kind === 'list') {
          check(
            Array.isArray(d) && d.length === 0,
            `${tp.name}.${f.name}: a list defaults to []`,
          );
        } else if (f.spec.kind === 'enum') {
          check(
            f.spec.values.includes(d),
            `${tp.name}.${f.name}: default not in the enum`,
          );
        }
      }
    }
  }
  // A 'fallback' default needs a type that can be built from nothing.
  for (const tp of types) {
    for (const f of tp.fields) {
      if (f.mode === 'default' && f.spec.kind === 'ref') {
        const target = byName.get(f.spec.name);
        check(
          target.fields.every(g => g.mode !== 'required'),
          `${tp.name}.${f.name}: ${target.name} has required fields, so it has no fallback`,
        );
      }
    }
  }
  return { version: contract.version, types, enums };
}

function cap(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** 'on-time' → 'onTime'. */
function camel(s) {
  return s.replace(/[-_ ]+([a-z0-9])/gi, (_, c) => c.toUpperCase());
}

/** 'on-time' → 'ON_TIME'. */
function screaming(s) {
  return s
    .replace(/[-\s]+/g, '_')
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .toUpperCase();
}

/** Wrap prose to a comment block of the given prefix. */
function commentLines(text, prefix, width = 78) {
  if (!text) return [];
  const words = text.split(/\s+/);
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && (prefix + line + ' ' + w).length > width) {
      lines.push(prefix + line);
      line = w;
    } else {
      line = line ? `${line} ${w}` : w;
    }
  }
  if (line) lines.push(prefix + line);
  return lines;
}

/** A KDoc/TSDoc block at `indent`, on one line when it fits. */
function docBlock(text, indent, width = 78) {
  if (!text) return [];
  const one = `${indent}/** ${text} */`;
  if (one.length <= width) return [one];
  return [
    `${indent}/**`,
    ...commentLines(text, `${indent} * `, width),
    `${indent} */`,
  ];
}

// ---------------------------------------------------------------- TypeScript

function tsType(spec) {
  switch (spec.kind) {
    case 'string':
      return 'string';
    case 'int':
    case 'long':
    case 'double':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'enum':
      return `WidgetContract${spec.enumName}`;
    case 'ref':
      return `WidgetContract${spec.name}`;
    case 'list':
      return `${tsType(spec.of)}[]`;
  }
  throw new Error(`unknown kind ${spec.kind}`);
}

function genTs(model) {
  const out = [];
  out.push('/**', ` * ${BANNER}`, ' *');
  out.push(
    ' * The v2 widget payload as the app writes it. A field marked optional',
  );
  out.push(
    ' * here may be left out when it equals its default; the native readers',
  );
  out.push(' * fill the default in. See the contract file for the rules.');
  out.push(' */', '');
  out.push(`export const WIDGET_CONTRACT_VERSION = ${model.version};`, '');
  for (const [name, values] of model.enums) {
    out.push(
      `export type WidgetContract${name} = ${values
        .map(v => `'${v}'`)
        .join(' | ')};`,
      '',
    );
  }
  for (const tp of model.types) {
    out.push(...docBlock(tp.doc, ''));
    out.push(`export type WidgetContract${tp.name} = {`);
    for (const f of tp.fields) {
      out.push(...docBlock(f.doc, '  '));
      const type = tsType(f.spec);
      if (f.mode === 'required') out.push(`  ${f.name}: ${type};`);
      else if (f.mode === 'default') out.push(`  ${f.name}?: ${type};`);
      else out.push(`  ${f.name}?: ${type} | null;`);
    }
    out.push('};', '');
  }
  const src = out.join('\n');
  // Formatted with the repo's own prettier so eslint's prettier rule and the
  // --check comparison both see what a human edit would produce.
  const prettier = require('prettier');
  const config = require(path.join(ROOT, '.prettierrc.js'));
  return prettier.format(src, { ...config, parser: 'typescript' });
}

// ---------------------------------------------------------------- Swift

function swiftType(spec) {
  switch (spec.kind) {
    case 'string':
      return 'String';
    case 'int':
    case 'long':
      return 'Int';
    case 'double':
      return 'Double';
    case 'bool':
      return 'Bool';
    case 'enum':
      return spec.enumName;
    case 'ref':
      return spec.name;
    case 'list':
      return `[${swiftType(spec.of)}]`;
  }
  throw new Error(`unknown kind ${spec.kind}`);
}

function swiftLiteral(spec, value) {
  if (spec.kind === 'ref') return `${spec.name}()`;
  if (spec.kind === 'list') return '[]';
  if (spec.kind === 'enum') return `.${camel(value)}`;
  if (spec.kind === 'string') return JSON.stringify(value);
  if (spec.kind === 'double')
    return Number.isInteger(value) ? `${value}.0` : String(value);
  return String(value);
}

/** The expression that reads one field, before required/default handling. */
function swiftRead(spec, key) {
  switch (spec.kind) {
    case 'string':
      return `c.wcValue(String.self, ${key})`;
    case 'bool':
      return `c.wcValue(Bool.self, ${key})`;
    case 'int':
    case 'long':
      return `c.wcInt(${key})`;
    case 'double':
      return `c.wcDouble(${key})`;
    case 'enum':
      return `c.wcValue(String.self, ${key}).flatMap(${spec.enumName}.init(rawValue:))`;
    case 'ref':
      return `c.wcValue(${spec.name}.self, ${key})`;
    case 'list': {
      const of = spec.of;
      if (of.kind === 'int' || of.kind === 'long')
        return `c.wcList(WCInt.self, ${key})?.map(\\.value)`;
      if (of.kind === 'double')
        return `c.wcList(WCDouble.self, ${key})?.map(\\.value)`;
      if (of.kind === 'enum')
        return `c.wcList(String.self, ${key})?.compactMap(${of.enumName}.init(rawValue:))`;
      return `c.wcList(${swiftType(of)}.self, ${key})`;
    }
  }
  throw new Error(`unknown kind ${spec.kind}`);
}

function genSwift(model) {
  const o = [];
  o.push(`// ${BANNER}`, '//');
  o.push(
    '// The v2 widget payload and the queues back to the app. Every reader here',
  );
  o.push(
    '// is lenient: a required field that is missing or mistyped makes its',
  );
  o.push(
    '// object unreadable; anything else falls back to its default or nil; a',
  );
  o.push(
    '// list drops the elements it cannot read. Formatting and time maths live',
  );
  o.push('// in WallClock.swift, never here.', '');
  o.push('import Foundation', '');
  o.push('enum WidgetContract {');
  o.push(`  static let version = ${model.version}`, '');
  for (const [name, values] of model.enums) {
    o.push(`  enum ${name}: String, Codable, Hashable {`);
    for (const v of values) {
      const c = camel(v);
      o.push(
        c === v ? `    case ${c}` : `    case ${c} = ${JSON.stringify(v)}`,
      );
    }
    o.push('  }', '');
  }
  for (const tp of model.types) {
    o.push(...commentLines(tp.doc, '  /// '));
    o.push(`  struct ${tp.name}: Codable, Hashable {`);
    for (const f of tp.fields) {
      o.push(...commentLines(f.doc, '    /// '));
      const ty = swiftType(f.spec);
      o.push(`    var ${f.name}: ${ty}${f.mode === 'nullable' ? '?' : ''}`);
    }
    o.push('');
    // Memberwise init with every default spelled out, so `Clock()` works and
    // tests can build a payload without restating what the defaults are.
    const params = tp.fields.map(f => {
      const ty = swiftType(f.spec) + (f.mode === 'nullable' ? '?' : '');
      if (f.mode === 'required') return `${f.name}: ${ty}`;
      if (f.mode === 'nullable') return `${f.name}: ${ty} = nil`;
      return `${f.name}: ${ty} = ${swiftLiteral(f.spec, f.spec.default)}`;
    });
    o.push(`    init(`);
    params.forEach((p, i) =>
      o.push(`      ${p}${i < params.length - 1 ? ',' : ''}`),
    );
    o.push('    ) {');
    for (const f of tp.fields) o.push(`      self.${f.name} = ${f.name}`);
    o.push('    }', '');
    o.push(`    enum CodingKeys: String, CodingKey {`);
    for (const f of tp.fields) o.push(`      case ${f.name}`);
    o.push('    }', '');
    o.push('    init(from decoder: Decoder) throws {');
    o.push('      let c = try decoder.container(keyedBy: CodingKeys.self)');
    for (const f of tp.fields) {
      const read = swiftRead(f.spec, `.${f.name}`);
      if (f.mode === 'required')
        o.push(`      ${f.name} = try c.wcRequire(${read}, .${f.name})`);
      else if (f.mode === 'nullable') o.push(`      ${f.name} = ${read}`);
      else
        o.push(
          `      ${f.name} = ${read} ?? ${swiftLiteral(
            f.spec,
            f.spec.default,
          )}`,
        );
    }
    o.push('    }');
    o.push('  }', '');
  }
  o.push('}', '');
  o.push(SWIFT_RUNTIME);
  return o.join('\n');
}

const SWIFT_RUNTIME = `// MARK: - Lenient reading

/// Decodes from any JSON value and keeps nothing: what a lossy list reads
/// to step past an element it could not use.
private struct WCSkip: Decodable {
  init(from decoder: Decoder) throws {}
}

/// A whole number, accepting a JSON number written with a fraction of zero
/// (Swift's own encoder writes a Double epoch as 1759000000000.0).
struct WCInt: Decodable, Hashable {
  let value: Int
  init(from decoder: Decoder) throws {
    let c = try decoder.singleValueContainer()
    if let i = try? c.decode(Int.self) {
      value = i
    } else {
      let d = try c.decode(Double.self)
      guard d.isFinite, d == d.rounded(), abs(d) < 9.0e15 else {
        throw DecodingError.dataCorruptedError(in: c, debugDescription: "not a whole number")
      }
      value = Int(d)
    }
  }
}

struct WCDouble: Decodable, Hashable {
  let value: Double
  init(from decoder: Decoder) throws {
    value = try decoder.singleValueContainer().decode(Double.self)
  }
}

extension KeyedDecodingContainer {
  fileprivate func wcValue<T: Decodable>(_ type: T.Type, _ key: Key) -> T? {
    (try? decodeIfPresent(type, forKey: key)) ?? nil
  }

  fileprivate func wcInt(_ key: Key) -> Int? {
    wcValue(WCInt.self, key)?.value
  }

  fileprivate func wcDouble(_ key: Key) -> Double? {
    wcValue(Double.self, key)
  }

  /// Every element that reads; the rest are skipped, not fatal.
  fileprivate func wcList<T: Decodable>(_ type: T.Type, _ key: Key) -> [T]? {
    guard (try? decodeNil(forKey: key)) == false,
          var items = try? nestedUnkeyedContainer(forKey: key)
    else { return nil }
    var out: [T] = []
    while !items.isAtEnd {
      if let v = try? items.decode(T.self) {
        out.append(v)
      } else if (try? items.decode(WCSkip.self)) == nil {
        break
      }
    }
    return out
  }

  fileprivate func wcRequire<T>(_ value: T?, _ key: Key) throws -> T {
    guard let value else {
      throw DecodingError.keyNotFound(
        key, .init(codingPath: codingPath, debugDescription: "required by the widget contract"))
    }
    return value
  }
}
`;

// ---------------------------------------------------------------- Kotlin

function ktType(spec) {
  switch (spec.kind) {
    case 'string':
      return 'String';
    case 'int':
      return 'Int';
    case 'long':
      return 'Long';
    case 'double':
      return 'Double';
    case 'bool':
      return 'Boolean';
    case 'enum':
      return spec.enumName;
    case 'ref':
      return spec.name;
    case 'list':
      return `List<${ktType(spec.of)}>`;
  }
  throw new Error(`unknown kind ${spec.kind}`);
}

function ktLiteral(spec, value) {
  if (spec.kind === 'ref') return `${spec.name}()`;
  if (spec.kind === 'list') return 'emptyList()';
  if (spec.kind === 'enum') return `${spec.enumName}.${screaming(value)}`;
  if (spec.kind === 'string') return JSON.stringify(value);
  if (spec.kind === 'long') return `${value}L`;
  if (spec.kind === 'double')
    return Number.isInteger(value) ? `${value}.0` : String(value);
  return String(value);
}

/** Converts one untyped JSON value (a list element) to the spec's type. */
function ktElement(spec) {
  switch (spec.kind) {
    case 'string':
      return '{ it as? String }';
    case 'bool':
      return '{ it as? Boolean }';
    case 'int':
      return '{ it.wcAsInt() }';
    case 'long':
      return '{ it.wcAsLong() }';
    case 'double':
      return '{ (it as? Number)?.toDouble() }';
    case 'enum':
      return `{ ${spec.enumName}.fromWire(it as? String) }`;
    case 'ref':
      return `{ ${spec.name}.fromJson(it as? JSONObject) }`;
  }
  throw new Error(`unknown list element kind ${spec.kind}`);
}

function ktRead(spec, key) {
  const k = JSON.stringify(key);
  switch (spec.kind) {
    case 'string':
      return `o.wcString(${k})`;
    case 'bool':
      return `o.wcBool(${k})`;
    case 'int':
      return `o.wcRaw(${k}).wcAsInt()`;
    case 'long':
      return `o.wcRaw(${k}).wcAsLong()`;
    case 'double':
      return `(o.wcRaw(${k}) as? Number)?.toDouble()`;
    case 'enum':
      return `${spec.enumName}.fromWire(o.wcString(${k}))`;
    case 'ref':
      return `${spec.name}.fromJson(o.wcRaw(${k}) as? JSONObject)`;
    case 'list':
      return `o.wcList(${k}) ${ktElement(spec.of)}`;
  }
  throw new Error(`unknown kind ${spec.kind}`);
}

function ktWrite(spec, expr) {
  switch (spec.kind) {
    case 'enum':
      return `${expr}.wire`;
    case 'ref':
      return `${expr}.toJson()`;
    case 'list': {
      const inner =
        spec.of.kind === 'enum'
          ? 'it.wire'
          : spec.of.kind === 'ref'
          ? 'it.toJson()'
          : 'it';
      return `JSONArray().apply { ${expr}.forEach { put(${inner}) } }`;
    }
    default:
      return expr;
  }
}

function genKotlin(model) {
  const o = [];
  o.push(`// ${BANNER}`, '//');
  o.push(
    '// The v2 widget payload and the queues back to the app. Every reader here',
  );
  o.push(
    '// is lenient: a required field that is missing or mistyped makes its',
  );
  o.push(
    '// object unreadable (null); anything else falls back to its default or',
  );
  o.push(
    '// null; a list drops the elements it cannot read. Formatting and time',
  );
  o.push('// maths live in WallClock.kt, never here.', '');
  o.push('package com.prayer_times.contract', '');
  o.push('import org.json.JSONArray');
  o.push('import org.json.JSONException');
  o.push('import org.json.JSONObject', '');
  o.push('object WidgetContract {');
  o.push(`  const val VERSION = ${model.version}`, '');
  for (const [name, values] of model.enums) {
    o.push(`  enum class ${name}(val wire: String) {`);
    values.forEach((v, i) =>
      o.push(
        `    ${screaming(v)}(${JSON.stringify(v)})${
          i < values.length - 1 ? ',' : ';'
        }`,
      ),
    );
    o.push('', '    companion object {');
    o.push(
      `      fun fromWire(s: String?): ${name}? = entries.firstOrNull { it.wire == s }`,
    );
    o.push('    }');
    o.push('  }', '');
  }
  for (const tp of model.types) {
    o.push(...docBlock(tp.doc, '  '));
    o.push(`  data class ${tp.name}(`);
    tp.fields.forEach(f => {
      o.push(...docBlock(f.doc, '    '));
      const ty = ktType(f.spec);
      let decl;
      if (f.mode === 'required') decl = `val ${f.name}: ${ty}`;
      else if (f.mode === 'nullable') decl = `val ${f.name}: ${ty}? = null`;
      else decl = `val ${f.name}: ${ty} = ${ktLiteral(f.spec, f.spec.default)}`;
      o.push(`    ${decl},`);
    });
    o.push('  ) {');
    o.push('    fun toJson(): JSONObject = JSONObject().apply {');
    for (const f of tp.fields) {
      const k = JSON.stringify(f.name);
      if (f.mode === 'nullable')
        o.push(`      ${f.name}?.let { put(${k}, ${ktWrite(f.spec, 'it')}) }`);
      else o.push(`      put(${k}, ${ktWrite(f.spec, f.name)})`);
    }
    o.push('    }', '');
    o.push('    companion object {');
    o.push(`      fun fromJson(o: JSONObject?): ${tp.name}? {`);
    o.push('        if (o == null) return null');
    o.push(`        return ${tp.name}(`);
    for (const f of tp.fields) {
      const read = ktRead(f.spec, f.name);
      if (f.mode === 'required')
        o.push(`          ${f.name} = ${read} ?: return null,`);
      else if (f.mode === 'nullable') o.push(`          ${f.name} = ${read},`);
      else
        o.push(
          `          ${f.name} = ${read} ?: ${ktLiteral(
            f.spec,
            f.spec.default,
          )},`,
        );
    }
    o.push('        )');
    o.push('      }', '');
    o.push(`      fun parse(json: String?): ${tp.name}? =`);
    o.push('        try {');
    o.push(
      '          if (json.isNullOrEmpty()) null else fromJson(JSONObject(json))',
    );
    o.push('        } catch (e: JSONException) {');
    o.push('          null');
    o.push('        }');
    o.push('    }');
    o.push('  }', '');
  }
  o.push('}', '');
  o.push(KOTLIN_RUNTIME);
  return o.join('\n');
}

const KOTLIN_RUNTIME = `// ── Lenient reading ────────────────────────────────────────────────────
//
// org.json's own opt* readers are not used: optString turns a JSON null into
// the four letters "null" on Android, and optInt turns a missing key into 0,
// which is how a renamed field used to draw as an empty label with no error.

private fun JSONObject.wcRaw(k: String): Any? = if (has(k) && !isNull(k)) opt(k) else null

private fun JSONObject.wcString(k: String): String? = wcRaw(k) as? String

private fun JSONObject.wcBool(k: String): Boolean? = wcRaw(k) as? Boolean

private fun Any?.wcAsLong(): Long? =
  when (this) {
    is Int -> toLong()
    is Long -> this
    is Number -> {
      val d = toDouble()
      if (d.isFinite() && d == Math.floor(d) && Math.abs(d) < 9.0e15) d.toLong() else null
    }
    else -> null
  }

private fun Any?.wcAsInt(): Int? =
  wcAsLong()?.let { if (it in Int.MIN_VALUE..Int.MAX_VALUE) it.toInt() else null }

private inline fun <T> JSONObject.wcList(k: String, element: (Any?) -> T?): List<T>? {
  val a = wcRaw(k) as? JSONArray ?: return null
  val out = ArrayList<T>(a.length())
  for (i in 0 until a.length()) {
    val v = if (a.isNull(i)) null else a.opt(i)
    element(v)?.let { out.add(it) }
  }
  return out
}
`;

// ---------------------------------------------------------------- main

function main() {
  const checkOnly = process.argv.includes('--check');
  const model = load(CONTRACT);
  const files = [
    [OUT.ts, genTs(model)],
    [OUT.swift, genSwift(model)],
    [OUT.kotlin, genKotlin(model)],
  ];
  let stale = 0;
  for (const [file, content] of files) {
    const rel = path.relative(ROOT, file);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) continue;
    if (checkOnly) {
      console.error(`stale: ${rel}`);
      stale += 1;
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`wrote ${rel}`);
    }
  }
  if (checkOnly && stale) {
    console.error('Run `npm run gen-widget-contract` and commit the result.');
    process.exit(1);
  }
}

if (require.main === module) main();

